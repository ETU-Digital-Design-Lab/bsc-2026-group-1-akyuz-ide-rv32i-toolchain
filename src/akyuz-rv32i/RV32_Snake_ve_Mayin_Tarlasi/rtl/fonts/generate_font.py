# ---------------------------------------------------------------------------
# Hex dosyası oluştur: 2048 satır, her biri "XX\n"
# ---------------------------------------------------------------------------
out_path = os.path.join(os.path.dirname(__file__), "font8x16.hex")

with open(out_path, "w") as f:
    for char_idx in range(128):
        rows = FONT.get(char_idx, [0x00] * 16)
        for row_byte in rows:
            f.write(f"{row_byte:02X}\n")

print(f"Font yazildi: {out_path}  ({128*16} satir)")
